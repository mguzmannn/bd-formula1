-- =====================================================================
-- Gestión de campeonatos de Fórmula 1 - Esquema de la base de datos
-- Motor: PostgreSQL 14 o superior
-- Trabajo Práctico de Bases de Datos - UTN FRSF
-- =====================================================================

-- Limpieza (permite volver a ejecutar el script)
DROP TABLE IF EXISTS penalizado, penalizacion, corre_en, clasificado,
    compite_para, carrera_principal, clasificacion, practica_libre,
    sesion, gran_premio, circuito, temporada, piloto, escuderia,
    motor, pais CASCADE;

-- ---------------------------------------------------------------------
-- Tablas de referencia
-- ---------------------------------------------------------------------
CREATE TABLE pais (
    id_pais     CHAR(3)      PRIMARY KEY,               -- código ISO de 3 letras
    nombre      VARCHAR(100) NOT NULL UNIQUE,
    continente  VARCHAR(30)  NOT NULL,
    CONSTRAINT ck_pais_iso CHECK (id_pais ~ '^[A-Z]{3}$')
);

CREATE TABLE motor (
    id_motor          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    marca_fabricante  VARCHAR(50) NOT NULL,
    modelo            VARCHAR(50) NOT NULL,
    CONSTRAINT uk_motor UNIQUE (marca_fabricante, modelo)
);

CREATE TABLE escuderia (
    id_escuderia               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                     VARCHAR(100) NOT NULL UNIQUE,
    anio_fundacion             SMALLINT     NOT NULL CHECK (anio_fundacion >= 1900),
    nombre_dir_deportivo       VARCHAR(100) NOT NULL,
    campeonatos_constructores  SMALLINT     NOT NULL DEFAULT 0 CHECK (campeonatos_constructores >= 0),
    id_motor                   INTEGER      NOT NULL REFERENCES motor (id_motor),
    id_pais                    CHAR(3)      NOT NULL REFERENCES pais (id_pais)
);

CREATE TABLE piloto (
    id_piloto            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR(100) NOT NULL,
    fecha_nac            DATE         NOT NULL,
    fecha_debut          DATE,
    campeonatos_ganados  SMALLINT     NOT NULL DEFAULT 0 CHECK (campeonatos_ganados >= 0),
    id_pais              CHAR(3)      NOT NULL REFERENCES pais (id_pais),   -- nacionalidad
    CONSTRAINT ck_piloto_debut CHECK (fecha_debut IS NULL OR fecha_debut > fecha_nac)
);

CREATE TABLE temporada (
    anio          SMALLINT PRIMARY KEY CHECK (anio >= 1950),
    fecha_inicio  DATE NOT NULL,
    fecha_fin     DATE NOT NULL,
    CONSTRAINT ck_temporada_fechas CHECK (fecha_fin > fecha_inicio)
);

CREATE TABLE circuito (
    id_circuito       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(100)  NOT NULL UNIQUE,
    tipo_circuito     VARCHAR(10)   NOT NULL,
    longitud          NUMERIC(5,3)  NOT NULL CHECK (longitud > 0),   -- en km
    cant_curvas       SMALLINT      NOT NULL CHECK (cant_curvas > 0),
    tiempo_record     INTERVAL,                                       -- mm:ss.mmm
    id_piloto_record  INTEGER       REFERENCES piloto (id_piloto),    -- quien ostenta el récord
    id_pais           CHAR(3)       NOT NULL REFERENCES pais (id_pais),
    CONSTRAINT ck_circuito_tipo   CHECK (tipo_circuito IN ('permanente', 'callejero', 'mixto')),
    CONSTRAINT ck_circuito_record CHECK ((tiempo_record IS NULL) = (id_piloto_record IS NULL))
);

-- ---------------------------------------------------------------------
-- Grandes Premios y sesiones
-- ---------------------------------------------------------------------
CREATE TABLE gran_premio (
    id_gp           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_oficial  VARCHAR(150) NOT NULL,
    fecha           DATE         NOT NULL,
    nro_ronda       SMALLINT     NOT NULL CHECK (nro_ronda > 0),
    id_circuito     INTEGER      NOT NULL REFERENCES circuito (id_circuito),
    anio            SMALLINT     NOT NULL REFERENCES temporada (anio),
    CONSTRAINT uk_gp_ronda  UNIQUE (anio, nro_ronda),
    CONSTRAINT uk_gp_nombre UNIQUE (anio, nombre_oficial)
);

-- Superclase de la especialización (Práctica libre / Clasificación / Carrera)
CREATE TABLE sesion (
    id_sesion          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_inicio       DATE     NOT NULL,
    hora_inicio        TIME     NOT NULL,
    duracion_estimada  SMALLINT NOT NULL CHECK (duracion_estimada > 0),   -- minutos
    id_gp              INTEGER  NOT NULL REFERENCES gran_premio (id_gp)
);

CREATE TABLE practica_libre (
    id_sesion  INTEGER PRIMARY KEY REFERENCES sesion (id_sesion),
    tipo       VARCHAR(3) NOT NULL CHECK (tipo IN ('FP1', 'FP2', 'FP3'))
);

CREATE TABLE clasificacion (
    id_sesion  INTEGER PRIMARY KEY REFERENCES sesion (id_sesion)
);

CREATE TABLE carrera_principal (
    id_sesion    INTEGER  PRIMARY KEY REFERENCES sesion (id_sesion),
    nro_vueltas  SMALLINT NOT NULL CHECK (nro_vueltas > 0)
);

-- ---------------------------------------------------------------------
-- Relaciones con atributos
-- ---------------------------------------------------------------------
-- Historial: un piloto corre para una única escudería por temporada.
CREATE TABLE compite_para (
    id_piloto     INTEGER  NOT NULL REFERENCES piloto (id_piloto),
    anio          SMALLINT NOT NULL REFERENCES temporada (anio),
    id_escuderia  INTEGER  NOT NULL REFERENCES escuderia (id_escuderia),
    nro_piloto    SMALLINT NOT NULL CHECK (nro_piloto BETWEEN 1 AND 99),
    PRIMARY KEY (id_piloto, anio),
    CONSTRAINT uk_numero_por_temporada UNIQUE (anio, nro_piloto)
);

CREATE TABLE clasificado (
    id_sesion          INTEGER  NOT NULL REFERENCES clasificacion (id_sesion),
    id_piloto          INTEGER  NOT NULL REFERENCES piloto (id_piloto),
    posicion_parrilla  SMALLINT NOT NULL CHECK (posicion_parrilla >= 1),
    t_q1               INTERVAL,
    t_q2               INTERVAL,
    t_q3               INTERVAL,
    PRIMARY KEY (id_sesion, id_piloto),
    CONSTRAINT uk_parrilla UNIQUE (id_sesion, posicion_parrilla),
    CONSTRAINT ck_q2_requiere_q1 CHECK (t_q2 IS NULL OR t_q1 IS NOT NULL),
    CONSTRAINT ck_q3_requiere_q2 CHECK (t_q3 IS NULL OR t_q2 IS NOT NULL)
);

CREATE TABLE corre_en (
    id_sesion                INTEGER     NOT NULL REFERENCES carrera_principal (id_sesion),
    id_piloto                INTEGER     NOT NULL REFERENCES piloto (id_piloto),
    posicion_final           SMALLINT    NOT NULL CHECK (posicion_final >= 1),
    tiempo_total             INTERVAL,                 -- NULL si no completó la carrera
    gap_al_ganador           INTERVAL,
    nro_vueltas_completadas  SMALLINT    NOT NULL CHECK (nro_vueltas_completadas >= 0),
    estado_finalizacion      VARCHAR(15) NOT NULL,
    puntos_obtenidos         SMALLINT    NOT NULL DEFAULT 0 CHECK (puntos_obtenidos >= 0),
    PRIMARY KEY (id_sesion, id_piloto),
    CONSTRAINT uk_posicion_final UNIQUE (id_sesion, posicion_final),
    CONSTRAINT ck_estado CHECK (estado_finalizacion IN ('completo', 'abandono', 'descalificado', 'no_largo'))
);

-- ---------------------------------------------------------------------
-- Penalizaciones
-- ---------------------------------------------------------------------
CREATE TABLE penalizacion (
    id_penalizacion    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo               VARCHAR(20)  NOT NULL,
    cantidad_segundos  SMALLINT     CHECK (cantidad_segundos > 0),
    motivo             VARCHAR(255) NOT NULL,
    vuelta_ocurrencia  SMALLINT     NOT NULL CHECK (vuelta_ocurrencia >= 1),
    comisario          VARCHAR(100) NOT NULL,
    CONSTRAINT ck_penalizacion_tipo   CHECK (tipo IN ('tiempo_agregado', 'drive_through', 'stop_and_go')),
    CONSTRAINT ck_penalizacion_tiempo CHECK (tipo <> 'tiempo_agregado' OR cantidad_segundos IS NOT NULL)
);

-- Cada penalización recae sobre un piloto que efectivamente corrió esa carrera.
CREATE TABLE penalizado (
    id_penalizacion  INTEGER PRIMARY KEY REFERENCES penalizacion (id_penalizacion),
    id_sesion        INTEGER NOT NULL,
    id_piloto        INTEGER NOT NULL,
    FOREIGN KEY (id_sesion, id_piloto) REFERENCES corre_en (id_sesion, id_piloto)
);

-- ---------------------------------------------------------------------
-- Índices sobre claves foráneas de uso frecuente
-- ---------------------------------------------------------------------
CREATE INDEX ix_gran_premio_anio       ON gran_premio (anio);
CREATE INDEX ix_gran_premio_circuito   ON gran_premio (id_circuito);
CREATE INDEX ix_sesion_gp              ON sesion (id_gp);
CREATE INDEX ix_compite_para_escuderia ON compite_para (id_escuderia);
CREATE INDEX ix_corre_en_piloto        ON corre_en (id_piloto);
CREATE INDEX ix_clasificado_piloto     ON clasificado (id_piloto);
